import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createScriptsStore } from '../selfhost/scripts-store.mjs';
const dir = await mkdtemp(path.join(os.tmpdir(), 'coach-scripts-'));
const store = createScriptsStore(dir);
await assert.rejects(createScriptsStore().read(), e => e.status === 503);
assert.deepEqual(await store.read(), []);
await assert.rejects(store.mutate('POST', { title: '', text: 'abc' }), e => e.status === 400);
await Promise.all([store.mutate('POST', { title: '稿 A', text: '第一段\n\n第二段' }), store.mutate('POST', { title: '稿 B', text: '测试' })]);
let items = await createScriptsStore(dir).read();
assert.equal(items.length, 2);
const item = items[0];
items = await store.mutate('PUT', { ...item, title: '新标题' });
assert.equal(items[0].title, '新标题');
await assert.rejects(store.mutate('PUT', { ...item, title: '旧设备覆盖' }), e => e.status === 409);
await assert.rejects(store.mutate('DELETE', { ...item }), e => e.status === 409);
items = await store.mutate('DELETE', items[0]);
assert.equal(items.length, 1);
await assert.rejects(store.mutate('POST', { title: '过长', text: 'a'.repeat(50001) }), e => e.status === 400);
console.log('PASS: persistent reload, concurrent writes, validation, revisions, delete, disabled storage. Temporary test data: ' + dir);
