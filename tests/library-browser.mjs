import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const bin = (process.env.PATH || '').split(path.delimiter).find(p => fs.existsSync(path.join(p, '../playwright/package.json')));
const pw = require(path.resolve(bin, '../playwright'));
const browser = await pw.chromium.launch({ channel: 'msedge', headless: true });
const credentials = { username: 'test', password: process.env.TEST_PASSWORD };
const page = await browser.newPage({ httpCredentials: credentials, viewport: { width: 1440, height: 1000 } });
const mobile = await browser.newPage({ httpCredentials: credentials, viewport: { width: 390, height: 844 } });
const base = process.env.TEST_BASE_URL;
const text = Array.from({ length: 30 }, (_, i) => `第${i + 1}段，欢迎来到健身工作室直播间。我们一起了解运动。`).join('\n\n');
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: '口播稿库', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles({ name: '试播稿.txt', mimeType: 'text/plain', buffer: Buffer.from(text) });
  await page.waitForFunction(expected => document.querySelector('textarea.library-editor')?.value === expected, text);
  assert.equal(await page.getByLabel('稿件正文', { exact: true }).inputValue(), text);
  await page.getByRole('button', { name: '保存到服务器', exact: true }).click();
  await page.getByRole('heading', { name: '试播稿', exact: true }).waitFor();
  await mobile.goto(base, { waitUntil: 'networkidle' });
  await mobile.getByRole('button', { name: '口播稿库', exact: true }).click();
  await mobile.getByRole('heading', { name: '试播稿', exact: true }).waitFor();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'outputs/library-desktop.png', fullPage: true });
  await mobile.screenshot({ path: 'outputs/library-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '开始提词', exact: true }).click();
  await page.locator('.prompter').evaluate(el => { el.scrollTop = 230; });
  await page.getByRole('button', { name: '临场问答', exact: true }).click();
  await page.getByRole('button', { name: '照稿直播', exact: true }).click();
  assert.ok(await page.locator('.prompter').evaluate(el => el.scrollTop) >= 220);
  await page.getByRole('button', { name: '口播稿库', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByLabel('稿件名称', { exact: true }).fill('修改标题');
  await page.getByRole('button', { name: '暖场话术', exact: true }).click();
  await page.getByRole('button', { name: '我的口播稿', exact: true }).click();
  assert.equal(await page.getByLabel('稿件名称', { exact: true }).inputValue(), '修改标题');
  await page.getByRole('button', { name: '保存到服务器', exact: true }).click();
  await page.getByRole('heading', { name: '修改标题', exact: true }).waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '删除', exact: true }).click();
  await page.getByText('已删除服务器稿件。', { exact: true }).waitFor();
  const Zip = require('jszip');
  const zip = new Zip();
  zip.file('[Content_Types].xml', '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>');
  zip.file('_rels/.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>');
  zip.file('word/document.xml', '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>欢迎来到工作室</w:t></w:r></w:p><w:p><w:r><w:t>这是第二段暖场话术</w:t></w:r></w:p></w:body></w:document>');
  await page.locator('input[type=file]').setInputFiles({ name: 'Word试稿.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: await zip.generateAsync({ type: 'nodebuffer' }) });
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="稿件正文"]')?.value.includes('这是第二段暖场话术'));
  assert.match(await page.getByLabel('稿件正文', { exact: true }).inputValue(), /欢迎来到工作室/);
  assert.equal((await page.request.post(base + '/api/scripts', { data: { title: 'x', text: 'x' }, headers: { Origin: 'https://wrong.example' } })).status(), 403);
  console.log('PASS: TXT/DOCX import, server save, separate mobile context, reading position, edit survives tabs, delete, origin rejection, screenshots.');
} catch (e) { await page.screenshot({ path: 'outputs/library-error.png', fullPage: true }); console.log(await page.locator('body').innerText()); throw e; } finally { await browser.close(); }
